import { jsPDF } from "jspdf";

interface EstimatePart {
  name: string;
  cost: number;
  severity: string;
}

interface EstimateData {
  id: string;
  totalCost: number;
  parts: EstimatePart[];
  summary: string;
  userName?: string;
  userEmail?: string;
  photoCount?: number;
}

/**
 * Generate and download a PDF report for a damage estimation.
 */
export function downloadEstimatePdf(data: EstimateData) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 20;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  // ─── Header ──────────────────────────────────────────────
  doc.setFontSize(22);
  doc.setFont("helvetica", "bold");
  doc.text("InsureVision", margin, y);
  y += 8;

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(120, 120, 120);
  doc.text("Vehicle Damage Estimation Report", margin, y);
  y += 12;

  // Separator line
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.5);
  doc.line(margin, y, pageWidth - margin, y);
  y += 10;

  // ─── Report Info ─────────────────────────────────────────
  doc.setTextColor(60, 60, 60);
  doc.setFontSize(9);

  const infoLines = [
    `Estimate ID: ${data.id}`,
    `Date: ${new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })}`,
  ];

  if (data.userName) infoLines.push(`Customer: ${data.userName}`);
  if (data.userEmail) infoLines.push(`Email: ${data.userEmail}`);
  if (data.photoCount) infoLines.push(`Photos Analyzed: ${data.photoCount}`);

  infoLines.forEach((line) => {
    doc.text(line, margin, y);
    y += 5;
  });

  y += 8;

  // ─── Summary ─────────────────────────────────────────────
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(30, 30, 30);
  doc.text("Summary", margin, y);
  y += 7;

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(60, 60, 60);
  const summaryLines = doc.splitTextToSize(data.summary, contentWidth);
  doc.text(summaryLines, margin, y);
  y += summaryLines.length * 5 + 10;

  // ─── Parts Breakdown ────────────────────────────────────
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(30, 30, 30);
  doc.text("Damage Breakdown", margin, y);
  y += 8;

  // Table header
  doc.setFillColor(245, 245, 245);
  doc.rect(margin, y - 4, contentWidth, 8, "F");
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(80, 80, 80);
  doc.text("Component", margin + 4, y);
  doc.text("Severity", margin + 90, y);
  doc.text("Cost", pageWidth - margin - 4, y, { align: "right" });
  y += 8;

  // Table rows
  doc.setFont("helvetica", "normal");
  doc.setTextColor(50, 50, 50);

  data.parts.forEach((part, i) => {
    if (i % 2 === 0) {
      doc.setFillColor(250, 250, 250);
      doc.rect(margin, y - 4, contentWidth, 7, "F");
    }

    doc.setFontSize(9);
    doc.text(part.name, margin + 4, y);

    // Severity with color
    if (part.severity === "High") doc.setTextColor(220, 50, 50);
    else if (part.severity === "Medium") doc.setTextColor(200, 150, 0);
    else doc.setTextColor(50, 160, 50);
    doc.text(part.severity, margin + 90, y);

    doc.setTextColor(50, 50, 50);
    doc.text(`$${part.cost.toLocaleString()}`, pageWidth - margin - 4, y, { align: "right" });
    y += 7;
  });

  y += 4;

  // Total
  doc.setDrawColor(200, 200, 200);
  doc.line(margin, y, pageWidth - margin, y);
  y += 8;

  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(30, 30, 30);
  doc.text("Estimated Total", margin + 4, y);
  doc.text(`$${data.totalCost.toLocaleString()}`, pageWidth - margin - 4, y, { align: "right" });
  y += 16;

  // ─── Disclaimer ──────────────────────────────────────────
  doc.setDrawColor(200, 200, 200);
  doc.line(margin, y, pageWidth - margin, y);
  y += 8;

  doc.setFontSize(8);
  doc.setFont("helvetica", "italic");
  doc.setTextColor(140, 140, 140);
  const disclaimer = "This estimate is generated by AI analysis and is for reference purposes only. Actual repair costs may vary based on physical inspection, parts availability, and labor rates. InsureVision is not liable for discrepancies between this estimate and final repair costs.";
  const disclaimerLines = doc.splitTextToSize(disclaimer, contentWidth);
  doc.text(disclaimerLines, margin, y);

  // ─── Footer ──────────────────────────────────────────────
  const pageHeight = doc.internal.pageSize.getHeight();
  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(160, 160, 160);
  doc.text(
    `Generated by InsureVision on ${new Date().toLocaleString()}`,
    pageWidth / 2,
    pageHeight - 10,
    { align: "center" }
  );

  // Download
  doc.save(`InsureVision-${data.id}.pdf`);
}
